let backTo = 'menu';
let current = 'menu';
const reduce = matchMedia('(prefers-reduced-motion: reduce)').matches;

// карточки и кнопки появляются по очереди
function stagger(root) {
  root.querySelectorAll('.tile,.item,.set,.ev,.card,.item-head,.bench,.stats,.add-set,.seg,.act').forEach((e, i) =>
    e.style.setProperty('--i', Math.min(i, 14)));
}
function restart(el, dx) {
  el.style.setProperty('--dx', dx + 'px');
  el.style.animation = 'none';
  void el.offsetHeight;
  el.style.animation = '';
}

function swap(id, dir) {
  document.body.classList.toggle('on-menu', id === 'menu');
  if (id === 'menu') {
    $('page').classList.add('hidden');
    $('menu').classList.remove('hidden');
    stagger($('menu'));
    restart($('menu'), dir * 16);
  } else {
    const s = id.startsWith('item:') ? window.itemScreen(id.slice(5)) : id.startsWith('farm:') ? window.farmScreen(id.slice(5)) : id.startsWith('craftitem:') ? window.craftCalc(id.slice(10)) : screens[id]();
    backTo = s.back;
    $('page-title').textContent = s.title;
    $('page-body').innerHTML = s.html;
    if (s.after) s.after();
    stagger($('page'));
    $('menu').classList.add('hidden');
    $('page').classList.remove('hidden');
    restart($('page'), dir * 16);
  }
  current = id;
  window.scrollTo(0, 0);
}

function go(id) {
  const same = id === current;
  const dir = same ? 0 : (id === 'menu' || id === backTo) ? -1 : 1;
  if (same || reduce) return swap(id, dir);
  const out = current === 'menu' ? $('menu') : $('page');
  out.style.setProperty('--dx', (-dir * 10) + 'px');
  out.classList.add('leave');
  setTimeout(() => { out.classList.remove('leave'); swap(id, dir); }, 140);
}

// искры над главным меню (пассивная анимация)
(function embers() {
  if (reduce) return;
  const box = document.createElement('div');
  box.className = 'embers';
  box.setAttribute('aria-hidden', 'true');
  for (let i = 0; i < 26; i++) {
    const e = document.createElement('i');
    const r = Math.random;
    e.className = 'c' + (i % 3);
    e.style.cssText = `--x:${(r() * 100).toFixed(1)}%;--s:${(2 + r() * 3.5) | 0}px;--d:${(7 + r() * 9).toFixed(1)}s;--t:${(-r() * 16).toFixed(1)}s;--w:${((r() - .5) * 60).toFixed(0)}px`;
    box.appendChild(e);
  }
  document.body.appendChild(box);
})();

document.addEventListener('click', e => {
  const b = e.target.closest('[data-go]');
  if (b) return go(b.dataset.go);
  const h = e.target.closest('.ev-head');
  if (h) {
    const open = h.getAttribute('aria-expanded') !== 'true';
    h.setAttribute('aria-expanded', open);
    h.parentElement.classList.toggle('open', open);
    if (open) h.parentElement.querySelectorAll('.ev-inner li').forEach((li, i) => li.style.setProperty('--k', Math.min(i, 12)));
  }
});
$('back').addEventListener('click', () => go(backTo));

